// Minimal HTML text-node escaping, shared by every widget that assembles
// markup as a template string instead of going through textContent.
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
